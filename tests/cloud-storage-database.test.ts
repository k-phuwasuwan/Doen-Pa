import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { storageSchema } from "./helpers/storage-schema";
const a = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", b = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";

test("cloud transactions and private Storage enforce ownership and survive retry/failure", async (t) => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth to anon, authenticated; insert into auth.users values('${a}'),('${b}');`);
  await db.exec(storageSchema);
  for (const file of readdirSync("supabase/migrations").filter((f) => f.endsWith(".sql")).sort()) await db.exec(readFileSync(`supabase/migrations/${file}`,"utf8"));
  const login = async (uid: string) => { await db.exec("reset role; set role authenticated"); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[uid]); };
  const photo = { id: "one", object_path: `${a}/record-photos/one.png`, mime_type: "image/png", size_bytes: 100 };
  const record = { id: "retry-id", place_id: "place-khao-yai", visited_at: "2026-01-01T12:00:00Z", note: "private", rating: 4 };
  await login(a);
  await db.query("insert into storage.objects(bucket_id,name,metadata) values('travel-photos',$1,$2)",[photo.object_path,{ size:100,mimetype:"image/png" }]);
  await db.query("select public.save_travel_record($1,$2)",[record,[photo]]);
  await db.query("select public.save_travel_record($1,$2)",[record,[photo]]);
  assert.equal((await db.query("select * from public.travel_records")).rows.length,1);
  assert.equal((await db.query("select * from public.photos")).rows.length,1);
  assert.equal((await db.query("delete from storage.objects returning *")).rows.length,0, "referenced bytes cannot be removed");
  assert.equal((await db.query("update storage.objects set name='overwritten' returning *")).rows.length,0, "uploads are immutable");
  await assert.rejects(db.query("select public.save_travel_record($1,$2)",[{ ...record,id:"failed" },[{ ...photo,id:"missing",object_path:`${a}/record-photos/missing.png` }]]));
  assert.equal((await db.query("select * from public.travel_records where id='failed'")).rows.length,0,"failed photo must roll back record");
  await login(b);
  assert.equal((await db.query("select * from storage.objects")).rows.length,0);
  assert.equal((await db.query("delete from storage.objects returning *")).rows.length,0);
  await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('travel-photos',$1)",[`${a}/record-photos/forged.png`]), { code:"42501" });
  await assert.rejects(db.query("select public.save_travel_record($1,$2)",[{...record,id:"foreign"},[photo]]));
  assert.equal((await db.query("select * from public.travel_records")).rows.length,0);
  await login(a);
  await db.query("select public.save_account_profile($1)",[{ name:"Original",username:"original",bio:"" }]);
  await assert.rejects(db.query("select public.save_account_profile($1,$2)",[{name:"Unsaved",username:"unsaved"},[{...photo,kind:"avatar"}]]));
  assert.deepEqual((await db.query("select name from public.profiles")).rows,[{name:"Original"}]);
  await db.query("delete from public.travel_records where id='retry-id'");
  assert.equal((await db.query("delete from storage.objects returning *")).rows.length,1,"unreferenced bytes can be cleaned");
  await db.exec("reset role; set role anon");
  await assert.rejects(db.query("select public.save_travel_record($1,$2)",[record,[]]), {code:"42501"});
  await db.exec("reset role");
  assert.deepEqual((await db.query("select public,file_size_limit from storage.buckets order by id")).rows,[{public:false,file_size_limit:1048576},{public:false,file_size_limit:5242880}]);
});
